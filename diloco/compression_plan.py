"""
Run plan for the pseudo-gradient compression study (PeerJ paper). Writes sweep files for
sweep.py; it never trains anything itself.

    python compression_plan.py tune                 # -> configs/compression_tune.yaml (80 short runs)
    python sweep.py configs/compression_tune.yaml
    python compression_plan.py select               # best outer LR per arm; edge cases -> compression_tune_edge.yaml
    python sweep.py configs/compression_tune_edge.yaml   # only if select asked for it, then select again
    python compression_plan.py final [--seeds 0 1 2 3 4] [--wandb_project NAME]
    python sweep.py configs/compression_final.yaml  # 20 arms x 5 seeds

Every arm is tuned the same way (same LR grid, same budget, seed 0), the FP32 baseline included.
"""
import argparse
import glob
import json
import math
import os

import yaml

# ---- fixed setting (spec: Training setup) ----
FIXED = dict(mode="diloco", k=4, H=100, outer_momentum=0.9, nesterov=True)
FULL_STEPS = 14_000
TUNE_STEPS = 3_500                         # 25% of the budget, same schedule shape
LR_GRID = [0.3, 0.5, 0.7, 1.0]
EDGE_EXTRA = {0.3: 0.2, 1.0: 1.3}          # one more point past a winning grid edge
TUNE_DIR = "results_compression/tune"
FINAL_DIR = "results_compression/final"

# ---- the 20 arms (spec: Run matrix) ----
ARMS = (
    [dict(compressor="fp32")]                                                      # baseline
    + [dict(compressor=c) for c in ["fp16", "int8", "int4", "int2", "sign"]]        # quantization
    + [dict(compressor=c, error_feedback=True) for c in ["int4", "int2", "sign"]]   # quantization + EF
    + [dict(compressor=f"topk{p}") for p in ["10", "5", "1", "0.1"]]                # top-k
    + [dict(compressor=f"topk{p}", error_feedback=True) for p in ["10", "5", "1", "0.1"]]
    + [dict(compressor="randk1", error_feedback=True),                              # controls
       dict(compressor="topk1_int4", error_feedback=True)]
    # SparseLoCo-style: EF (beta 0.95, their best at 512M, App. H) replaces outer momentum
    + [dict(compressor="topk1", error_feedback=True, ef_beta=0.95, outer_momentum=0.0, nesterov=False)]
)
assert len(ARMS) == 20


def arm_key(d):
    return (d.get("compressor"), bool(d.get("error_feedback", False)), float(d.get("ef_beta", 1.0)),
            float(d.get("outer_momentum", FIXED["outer_momentum"])))


def write(path, spec, header):
    with open(path, "w") as f:
        f.write(header)
        yaml.safe_dump(spec, f, sort_keys=False, default_flow_style=None, width=200)
    n = len(spec.get("runs", []))
    print(f"wrote {path} ({n} runs)")


def cmd_tune(_):
    runs = [{**arm, "outer_lr": lr} for arm in ARMS for lr in LR_GRID]
    base = {**FIXED, "steps": TUNE_STEPS, "seed": 0, "out_dir": TUNE_DIR}
    write("configs/compression_tune.yaml", {"base": base, "runs": runs},
          "# Outer-LR tuning for the compression study: every arm x every LR, seed 0, 25% budget.\n"
          "# Generated by compression_plan.py tune -- edit ARMS/LR_GRID there, not here.\n")


def tuning_results():
    """arm_key -> {outer_lr: final val loss (inf if diverged)}"""
    res = {}
    for f in glob.glob(os.path.join(TUNE_DIR, "*.json")):
        s = json.load(open(f))
        c = s["config"]
        if c["steps"] != TUNE_STEPS:
            continue
        loss = s["final_val_loss"] if not s["diverged"] and math.isfinite(s["final_val_loss"]) else math.inf
        res.setdefault(arm_key(c), {})[c["outer_lr"]] = loss
    return res


def best_lrs():
    """Returns (arm -> chosen LR, list of edge runs still needed, list of arms with missing runs)."""
    res = tuning_results()
    chosen, edge_runs, missing = {}, [], []
    for arm in ARMS:
        got = res.get(arm_key(arm), {})
        if any(lr not in got for lr in LR_GRID):
            missing.append(arm)
            continue
        best = min(got, key=got.get)
        extra = EDGE_EXTRA.get(best)
        if extra is not None and extra not in got:
            edge_runs.append({**arm, "outer_lr": extra})
            continue
        chosen[arm_key(arm)] = (best, got)
    return chosen, edge_runs, missing


def cmd_select(_):
    chosen, edge_runs, missing = best_lrs()
    for arm in missing:
        print("missing tuning runs for", arm)
    for arm in ARMS:
        if arm_key(arm) in chosen:
            best, got = chosen[arm_key(arm)]
            grid = "  ".join(f"{lr}:{v:.4f}" for lr, v in sorted(got.items()))
            print(f"{str(arm):95s} best {best}   [{grid}]")
    if edge_runs:
        base = {**FIXED, "steps": TUNE_STEPS, "seed": 0, "out_dir": TUNE_DIR}
        write("configs/compression_tune_edge.yaml", {"base": base, "runs": edge_runs},
              "# Best LR fell on a grid edge for these arms: one more point past the edge.\n"
              "# Run with sweep.py, then `python compression_plan.py select` again.\n")


def cmd_final(a):
    chosen, edge_runs, missing = best_lrs()
    if missing or edge_runs:
        raise SystemExit("tuning incomplete: run `python compression_plan.py select` and finish the "
                         "listed runs first")
    base = {**FIXED, "steps": FULL_STEPS, "out_dir": FINAL_DIR, "final_eval_iters": 200}
    if a.wandb_project:
        base["wandb_project"] = a.wandb_project
    runs = [{**arm, "outer_lr": chosen[arm_key(arm)][0], "seed": s} for s in a.seeds for arm in ARMS]
    write("configs/compression_final.yaml", {"base": base, "runs": runs},
          "# Final runs: every arm at its tuned outer LR, full budget. Seeds are the outer loop,\n"
          "# so stopping early still leaves complete seeds for every arm.\n"
          "# Generated by compression_plan.py final.\n")


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("tune")
    sub.add_parser("select")
    f = sub.add_parser("final")
    f.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    f.add_argument("--wandb_project", default="")
    a = p.parse_args()
    {"tune": cmd_tune, "select": cmd_select, "final": cmd_final}[a.cmd](a)


if __name__ == "__main__":
    main()
